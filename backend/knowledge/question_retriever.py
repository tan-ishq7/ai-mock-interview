"""
Retrieve ML questions using vector similarity search (Supabase pgvector with local vector fallback).

Matches questions relevant to the candidate's identified field (NLP, CV, etc.)
using cosine similarity on 384-dim embeddings generated by all-MiniLM-L6-v2.
"""

import logging
from pathlib import Path
from typing import Any
import numpy as np

from sentence_transformers import SentenceTransformer

from backend.database.supabase_client import get_supabase
from backend.knowledge.question_indexer import _parse_markdown

logger = logging.getLogger(__name__)

EMBEDDING_MODEL_NAME = "all-MiniLM-L6-v2"
ML_QUESTIONS_PATH = Path(__file__).parent / "ml_questions.md"

# Lazy-loaded singletons
_model: SentenceTransformer | None = None
_local_questions: list[dict[str, str]] | None = None
_local_embeddings: np.ndarray | None = None


def _get_model() -> SentenceTransformer:
    global _model
    if _model is None:
        _model = SentenceTransformer(EMBEDDING_MODEL_NAME)
    return _model


def _get_local_question_bank() -> tuple[list[dict[str, str]], np.ndarray]:
    """Load and embed local questions once for fast fallback retrieval."""
    global _local_questions, _local_embeddings
    if _local_questions is None or _local_embeddings is None:
        _local_questions = _parse_markdown(ML_QUESTIONS_PATH)
        model = _get_model()
        texts = [f"{q['category']}: {q['question']}" for q in _local_questions]
        _local_embeddings = model.encode(texts, normalize_embeddings=True)
    return _local_questions, _local_embeddings


def _retrieve_local_vector_search(query_embedding: list[float], num_questions: int) -> list[dict[str, Any]]:
    """Perform local cosine similarity search against markdown question bank."""
    questions, embeddings = _get_local_question_bank()
    if not questions or embeddings.size == 0:
        return []

    q_vec = np.array(query_embedding, dtype=np.float32)
    scores = np.dot(embeddings, q_vec)
    top_indices = np.argsort(scores)[::-1][:num_questions]

    return [
        {
            "question": questions[idx]["question"],
            "answer": questions[idx]["answer"],
            "category": questions[idx]["category"],
        }
        for idx in top_indices
    ]


def retrieve_questions_by_field(
    field: str,
    num_questions: int = 5,
) -> list[dict[str, Any]]:
    """Retrieve ML questions most relevant to the candidate's field.

    Uses the field name (e.g. "NLP", "Computer Vision") to generate a query
    embedding and finds the closest questions via cosine similarity.

    Tries Supabase pgvector first; seamlessly falls back to local semantic vector
    search if Supabase is offline, paused, or unseeded.

    Parameters
    ----------
    field:
        The candidate's primary ML field.
    num_questions:
        Number of questions to retrieve.

    Returns
    -------
    list of dicts with keys: question, answer, category.
    """
    model = _get_model()
    query = f"Machine learning questions about {field}"
    query_embedding = model.encode(query, normalize_embeddings=True).tolist()

    # 1. Try Supabase vector RPC
    try:
        supabase = get_supabase()
        result = supabase.rpc(
            "match_ml_questions",
            {
                "query_embedding": query_embedding,
                "match_count": num_questions,
            },
        ).execute()

        if result.data:
            return [
                {
                    "question": r["question"],
                    "answer": r["answer"],
                    "category": r["category"],
                }
                for r in result.data
            ]
    except Exception as exc:
        logger.warning("Supabase RPC match_ml_questions unavailable: %s", exc)

    # 2. Try Supabase category filter fallback
    try:
        supabase = get_supabase()
        result = (
            supabase.table("ml_questions")
            .select("question, answer, category")
            .ilike("category", f"%{field}%")
            .limit(num_questions)
            .execute()
        )

        questions = result.data if result.data else []

        if len(questions) < num_questions:
            remaining = num_questions - len(questions)
            existing_ids = {q["question"] for q in questions}
            general = (
                supabase.table("ml_questions")
                .select("question, answer, category")
                .limit(remaining + 5)
                .execute()
            )
            for q in general.data or []:
                if q["question"] not in existing_ids and len(questions) < num_questions:
                    questions.append(q)

        if questions:
            return questions
    except Exception as exc:
        logger.warning("Supabase table query unavailable: %s", exc)

    # 3. Local semantic vector search fallback (100% reliable)
    logger.info("Using local vector similarity search for field: '%s'", field)
    return _retrieve_local_vector_search(query_embedding, num_questions)
