CREATE EXTENSION IF NOT EXISTS vector;


-- ============================================================
-- STEP 2: candidates
-- Stores parsed resume data for each candidate who uploads a PDF.
-- ============================================================
CREATE TABLE IF NOT EXISTS candidates (
    id                  UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    name                TEXT        NOT NULL,
    email               TEXT        NOT NULL,
    resume_raw_text     TEXT        DEFAULT '',
    resume_sections     JSONB       DEFAULT '{}'::jsonb,
    -- resume_sections stores: about_me, education[], work_experience[], projects[], technical_skills{}
    identified_field    TEXT        DEFAULT '',
    -- identified_field: e.g. "NLP", "Computer Vision", "Agentic AI", "Backend Engineering"
    primary_project     JSONB       DEFAULT '{}'::jsonb,
    -- primary_project: { title, description, technologies[] }
    secondary_project   JSONB       DEFAULT '{}'::jsonb,
    created_at          TIMESTAMPTZ DEFAULT now()
);


-- ============================================================
-- STEP 3: interview_sessions
-- One row per interview session. A candidate can have multiple sessions.
-- ============================================================
CREATE TABLE IF NOT EXISTS interview_sessions (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    candidate_id    UUID        NOT NULL REFERENCES candidates(id) ON DELETE CASCADE,
    started_at      TIMESTAMPTZ DEFAULT now(),
    ended_at        TIMESTAMPTZ,
    current_phase   INT         DEFAULT 1 CHECK (current_phase BETWEEN 1 AND 5),
    status          TEXT        DEFAULT 'in_progress'
                                CHECK (status IN ('in_progress', 'completed', 'cancelled')),
    created_at      TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sessions_candidate
    ON interview_sessions(candidate_id);


-- ============================================================
-- STEP 4: conversation_messages
-- Full transcript of every message (interviewer + candidate) per session.
-- NOTE: The current code does NOT write here yet — this is the correct
--       schema for when that feature is added.
-- ============================================================
CREATE TABLE IF NOT EXISTS conversation_messages (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id      UUID        NOT NULL REFERENCES interview_sessions(id) ON DELETE CASCADE,
    phase           INT         NOT NULL CHECK (phase BETWEEN 1 AND 5),
    role            TEXT        NOT NULL CHECK (role IN ('assistant', 'user', 'system')),
    content         TEXT        NOT NULL,
    depth_level     INT,        -- only set for phases 2/3 (1-5)
    is_hint         BOOLEAN     DEFAULT false,
    hint_recovery   BOOLEAN,    -- true if candidate recovered after hint
    anxiety_detected BOOLEAN    DEFAULT false,
    created_at      TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_messages_session
    ON conversation_messages(session_id, phase);


-- ============================================================
-- STEP 5: ml_questions
-- Knowledge base for Phase 4 factual questions.
-- Each question has a 384-dim embedding for vector similarity search.
-- The embedding is generated by all-MiniLM-L6-v2 (runs locally in Python).
-- ============================================================
CREATE TABLE IF NOT EXISTS ml_questions (
    id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    question    TEXT        NOT NULL,
    answer      TEXT        NOT NULL,   -- ground truth, never shown to candidate
    category    TEXT        DEFAULT '', -- "NLP", "Computer Vision", "Reinforcement Learning", etc.
    source      TEXT        DEFAULT '', -- where this question came from
    embedding   VECTOR(384),            -- all-MiniLM-L6-v2 output dimension
    created_at  TIMESTAMPTZ DEFAULT now()
);

-- HNSW index for fast approximate nearest-neighbor search on embeddings
-- This makes vector search ~100x faster at scale vs brute force
CREATE INDEX IF NOT EXISTS idx_ml_questions_embedding
    ON ml_questions USING hnsw (embedding vector_cosine_ops);


-- ============================================================
-- STEP 6: evaluations
-- Per-phase scores for each session.
-- One row per phase per session (so up to 5 rows per session).
-- ============================================================
CREATE TABLE IF NOT EXISTS evaluations (
    id                      UUID    PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id              UUID    NOT NULL REFERENCES interview_sessions(id) ON DELETE CASCADE,
    phase                   INT     NOT NULL CHECK (phase BETWEEN 1 AND 5),

    -- General score for this phase (0-100)
    score                   FLOAT   DEFAULT 0,

    -- Phase 2/3 (Socratic deep-dive) fields
    max_depth_reached       INT     DEFAULT 0,  -- 0-5
    hints_given             INT     DEFAULT 0,
    hints_recovered         INT     DEFAULT 0,

    -- Phase 4 (factual) fields
    factual_correct         INT     DEFAULT 0,
    factual_total           INT     DEFAULT 0,

    -- Phase 5 (behavioral) fields
    behavioral_visionary    FLOAT   DEFAULT 0,  -- 0-10
    behavioral_grounded     FLOAT   DEFAULT 0,  -- 0-10
    behavioral_teamplayer   FLOAT   DEFAULT 0,  -- 0-10

    -- Any extra data (per-response evaluations, etc.)
    details                 JSONB   DEFAULT '{}'::jsonb,

    created_at              TIMESTAMPTZ DEFAULT now(),

    UNIQUE(session_id, phase)  -- one evaluation row per phase per session
);

CREATE INDEX IF NOT EXISTS idx_evaluations_session
    ON evaluations(session_id);


-- ============================================================
-- STEP 7: reports
-- Final interview report — one per session.
-- ============================================================
CREATE TABLE IF NOT EXISTS reports (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id      UUID        NOT NULL REFERENCES interview_sessions(id) ON DELETE CASCADE,
    candidate_id    UUID        NOT NULL REFERENCES candidates(id),
    -- candidate_id is denormalized (redundant with session→candidate) for fast queries

    overall_score   FLOAT       DEFAULT 0,  -- 0-100, weighted average of all phases

    phase_scores    JSONB       DEFAULT '{}'::jsonb,
    -- phase_scores: { phase_2: {...}, phase_3: {...}, phase_4: {...}, phase_5: {...} }

    strengths       TEXT[]      DEFAULT '{}',
    weaknesses      TEXT[]      DEFAULT '{}',
    recommendations TEXT[]      DEFAULT '{}',
    report_text     TEXT        DEFAULT '',  -- full LLM-generated narrative

    created_at      TIMESTAMPTZ DEFAULT now(),

    UNIQUE(session_id)  -- one report per session
);

CREATE INDEX IF NOT EXISTS idx_reports_candidate
    ON reports(candidate_id);


-- ============================================================
-- STEP 8: match_ml_questions function
-- Called by the Python backend via supabase.rpc("match_ml_questions", {...})
-- Finds the most relevant ML questions for a candidate's field using
-- cosine similarity on embeddings.
--
-- How it works:
--   1. Python encodes the candidate's field with all-MiniLM-L6-v2
--   2. Passes the 384-dim vector to this function
--   3. Postgres searches the HNSW index for the closest vectors
--   4. Returns top match_count questions with their answers
-- ============================================================
CREATE OR REPLACE FUNCTION match_ml_questions(
    query_embedding VECTOR(384),
    match_count     INT DEFAULT 5
)
RETURNS TABLE (
    id          UUID,
    question    TEXT,
    answer      TEXT,
    category    TEXT,
    similarity  FLOAT
)
LANGUAGE sql STABLE
AS $$
    SELECT
        id,
        question,
        answer,
        category,
        1 - (embedding <=> query_embedding) AS similarity
        -- <=> is cosine distance (0=identical, 2=opposite)
        -- 1 - distance = similarity (1=identical, -1=opposite)
    FROM ml_questions
    WHERE embedding IS NOT NULL
    ORDER BY embedding <=> query_embedding
    LIMIT match_count;
$$;


